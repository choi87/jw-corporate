export function pageLocale(pathname: string) {
  const [, prefix] = pathname.split('/');
  const index = languages.findIndex(({ code }) => code !== 'ko' && code === prefix);
  const { code, tag, og } = languages[index < 0 ? 0 : index];
  const path = index < 0 ? pathname : pathname.slice(prefix.length + 1) || '/';
  return {
    code, tag, og, path,
    t: (text: string) => messages[text]?.[index - 1] ?? text,
    href: (url: string) => code === 'ko' ? url : '/' + code + url,
  };
}

export function languagePath(code: Locale, path: string) {
  return code === 'ko' ? path : '/' + code + path;
}
